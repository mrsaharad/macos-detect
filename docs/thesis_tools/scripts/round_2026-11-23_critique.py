def wilson(k, n, z=1.96):
    p = k / n
    d = 1 + z * z / n
    c = (p + z * z / (2 * n)) / d
    h = z * (p * (1 - p) / n + z * z / (4 * n * n)) ** 0.5 / d
    return (max(0.0, c - h), min(1.0, c + h))


def frac(r, ci=True):
    """{'k','n','rate','ci95'} -> '8/21 (38.1%)' + บรรทัดใหม่ '[20.8–59.1%]'"""
    s = f"{r['k']}/{r['n']} ({r['rate'] * 100:.1f}%)"
    if ci:
        lo, hi = r["ci95"]
        s += f"\n[{lo * 100:.1f}–{hi * 100:.1f}%]"
    return s


