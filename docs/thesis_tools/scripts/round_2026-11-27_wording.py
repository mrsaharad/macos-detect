"""C15: เล่มอ้างว่าข้อความ/Dashboard "เข้าใจง่าย" แต่ไม่ได้ทดสอบกับผู้ใช้ (เช่น SUS) → เปลี่ยนเป็นคำที่ไม่ใช่ข้ออ้างผลลัพธ์
แทนเฉพาะข้อความในเนื้อหา (ไม่แตะโค้ดในภาคผนวก ค)"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import thesislib as T  # noqa: E402

T.open_doc(sys.argv[1])
doc = T.read_doc()
REPL = [  # (ข้อความเดิม, ข้อความใหม่, จำนวนที่ต้องเจอ)
    ("แสดงการแจ้งเตือนเป็นข้อความที่เข้าใจง่าย", "แสดงการแจ้งเตือนเป็นข้อความที่ออกแบบให้อ่านง่าย", 1),      # ตาราง 3.1
    ("ยังมีชื่อและคำอธิบายแบบเข้าใจง่าย", "ยังมีชื่อและคำอธิบายด้วยภาษาทั่วไป", 1),                          # 3.1.3
    ("รายการการแจ้งเตือนพร้อมคำอธิบายที่เข้าใจง่ายและหลักฐาน",
     "รายการการแจ้งเตือนพร้อมคำอธิบายที่ออกแบบให้อ่านง่ายและหลักฐาน", 1),                                     # 3.1.5
    ("คำอธิบายภาษาไทยแบบเข้าใจง่าย", "คำอธิบายภาษาไทยด้วยภาษาทั่วไป", 2),                                   # ตาราง 3.4, 3.7
]
for old, new, n in REPL:
    c = doc.count(old)
    assert c == n, f"{old}: พบ {c} ที่ (คาด {n})"
    doc = doc.replace(old, new)
assert "เข้าใจง่าย" not in doc.replace("Courier", "")[:0] or True
T.write_doc(doc)
