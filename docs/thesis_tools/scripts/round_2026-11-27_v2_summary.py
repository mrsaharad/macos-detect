E = T.Ed(T.read_doc())


def text_of(m):
    return html.unescape(T.ptext(m))


def rw(prefix, text):
    E.rewrite(prefix, text)


def app(prefix, extra):
    m = E.para(prefix)
    E.put(m, T.rewrite_para(m, text_of(m) + " " + extra))


def add_after(prefix, text):
    """ย่อหน้าใหม่ที่ใช้รูปแบบเดียวกับย่อหน้า prefix (รวมเลขลำดับของรายการ)"""
    m = E.para(prefix)
    E.doc = E.doc[:m.end()] + T.rewrite_para(m, text) + E.doc[m.end():]


def delete(prefix):
    E.put(E.para(prefix), "")


